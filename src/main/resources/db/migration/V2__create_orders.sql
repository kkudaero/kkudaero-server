CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL,
    product_name VARCHAR(200) NOT NULL,
    purchase_source VARCHAR(100) NOT NULL,
    purchase_date DATE NOT NULL,
    item_price_jpy NUMERIC(12, 0) NOT NULL,
    local_shipping_fee_jpy NUMERIC(12, 0) NOT NULL,
    recipient_name VARCHAR(512),
    personal_customs_code VARCHAR(512),
    local_tracking_number VARCHAR(100),
    international_tracking_number VARCHAR(100),
    status VARCHAR(30) NOT NULL,
    memo VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_orders_seller FOREIGN KEY (seller_id) REFERENCES sellers (id)
);

CREATE INDEX idx_orders_seller_created ON orders (seller_id, created_at DESC, id DESC);
