ALTER TABLE orders ADD COLUMN customs_status VARCHAR(200);
ALTER TABLE orders ADD COLUMN customs_checked_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL,
    order_id BIGINT,
    type VARCHAR(50) NOT NULL,
    message VARCHAR(500) NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notifications_seller FOREIGN KEY (seller_id) REFERENCES sellers (id),
    CONSTRAINT fk_notifications_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);

CREATE INDEX idx_notifications_seller_created ON notifications (seller_id, created_at DESC, id DESC);
